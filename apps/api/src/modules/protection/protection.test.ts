// =============================================================================
// Anti-leak tests (Session 09) — D1 forensic watermark + D2 video trace.
//
// Same posture as every suite before it: no real database, bucket or image
// library. The shared in-memory Prisma fake, a fake StorageClient and a fake
// ImageProcessor whose `watermark` echoes its label back into the bytes (so the
// "rendered" watermark text is inspectable), wired through `buildServer`; auth
// cookies come from the real register→verify→login flow.
//
// The properties under test, straight from the session's acceptance criteria:
//   * two viewers of the same content get different codes
//   * the same viewer twice in one minute gets the same code; a minute later,
//     a different one
//   * one AuditLog row per serve, and a code round-trips to the right viewer
//     through it — and only through it
//   * the watermark text carries no substring of the viewer's email or id
//   * video serves return the code as JSON, generated by the same helper, with
//     the same audit trail
//   * WATERMARK_TRACE_SECRET is validated at boot (present, ≥ 32 chars)
// =============================================================================
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { buildServer } from '../../index.js';
import type { PrismaClient } from '../../lib/prisma.js';
import type { StorageClient } from '../../lib/storage.js';
import type { ImageProcessor } from '../../lib/image.js';
import {
  createFakeEmailer,
  createFakePrisma,
  seedContent,
  seedGenerationJob,
  seedProfile,
  type FakePrisma,
} from '../../test/fake-prisma.js';
import {
  TRACE_CODE_LENGTH,
  WATERMARK_BRAND,
  computeTraceCode,
  createTraceRecorder,
  traceWatermarkLabel,
} from './trace.js';

const TRACE_RE = /^[A-Z2-7]{8}$/;
const LABEL_RE = new RegExp(`^${WATERMARK_BRAND} • ([A-Z2-7]{${TRACE_CODE_LENGTH}})$`);
const WATERMARK_MARKER = 'WATERMARKED:';

// ── Fakes ────────────────────────────────────────────────────────────────────
function createFakeStorage(): StorageClient {
  return {
    uploadFile: vi.fn(async (_b: string, key: string) => key),
    getSignedUrl: vi.fn(
      async (_b: string, key: string, ttl: number) => `https://signed.example/${key}?ttl=${ttl}`,
    ),
    getObject: vi.fn(async () => Buffer.from('RAW-IMAGE-BYTES')),
    deleteFile: vi.fn(async () => {}),
  };
}

/** Echoes the label into the output so the test can read the "rendered" mark. */
function createFakeImages(): ImageProcessor {
  return {
    getDimensions: vi.fn(async () => ({ width: 800, height: 600 })),
    watermark: vi.fn(async (_buffer: Buffer, label: string) =>
      Buffer.from(`${WATERMARK_MARKER}${label}`),
    ),
  };
}

interface Harness {
  app: Awaited<ReturnType<typeof buildServer>>;
  prisma: FakePrisma;
  images: ImageProcessor;
}

async function makeApp(): Promise<Harness> {
  const prisma = createFakePrisma();
  const images = createFakeImages();
  const app = await buildServer({
    prisma: prisma as unknown as PrismaClient,
    emailer: createFakeEmailer(),
    storage: createFakeStorage(),
    images,
  });
  return { app, prisma, images };
}

async function loginAs(
  h: Harness,
  role: 'model' | 'subscriber',
  email: string,
): Promise<{ cookie: string; userId: string; email: string }> {
  await h.app.inject({
    method: 'POST',
    url: '/api/auth/register',
    payload: { email, password: 'supersecret', displayName: `Test ${role}`, role },
  });
  const user = h.prisma.__users.find((u) => u.email === email)!;
  await h.app.inject({ method: 'GET', url: `/api/auth/verify-email?token=${user.verifyToken}` });
  const login = await h.app.inject({
    method: 'POST',
    url: '/api/auth/login',
    payload: { email, password: 'supersecret' },
  });
  return {
    cookie: login.cookies.find((c) => c.name === 'access_token')!.value,
    userId: user.id,
    email,
  };
}

function grantAccess(h: Harness, contentId: string, userId: string) {
  h.prisma.__accesses.push({
    id: `acc_seed_${h.prisma.__accesses.length + 1}`,
    contentId,
    userId,
    grantReason: 'subscription_standard',
    grantedAt: new Date(),
    expiresAt: null,
  });
}

const serve = (h: Harness, contentId: string, cookie: string) =>
  h.app.inject({
    method: 'GET',
    url: `/api/content/${contentId}/serve`,
    cookies: { access_token: cookie },
  });

/** The trace code rendered into a served image body. */
function codeIn(body: string): string {
  expect(body.startsWith(WATERMARK_MARKER)).toBe(true);
  const match = body.slice(WATERMARK_MARKER.length).match(LABEL_RE);
  expect(match, `watermark text "${body}" is not brand + trace code`).not.toBeNull();
  return match![1];
}

const serveRows = (h: Harness, action: string) =>
  h.prisma.__auditLogs.filter((row) => row.action === action);

type TraceMeta = { viewerId: string; traceCode: string; servedAt: string };

/** The forensic lookup itself: code → AuditLog row → viewer. */
function resolveCode(h: Harness, code: string) {
  return h.prisma.__auditLogs.filter((row) => (row.metadata as TraceMeta)?.traceCode === code);
}

// =============================================================================
describe('computeTraceCode (pure)', () => {
  const base = {
    secret: 'unit-test-secret-at-least-32-characters-long!!',
    entityId: 'content_1',
    viewerId: 'user_a',
    servedAt: new Date('2026-09-11T12:00:10.000Z'),
  };

  it('is 8 chars of RFC 4648 base32 and deterministic for identical inputs', () => {
    const a = computeTraceCode(base);
    expect(a).toMatch(TRACE_RE);
    expect(a).toHaveLength(TRACE_CODE_LENGTH);
    expect(computeTraceCode({ ...base })).toBe(a);
  });

  it('is stable within a minute and changes across the minute boundary', () => {
    const a = computeTraceCode(base);
    expect(computeTraceCode({ ...base, servedAt: new Date('2026-09-11T12:00:59.999Z') })).toBe(a);
    expect(computeTraceCode({ ...base, servedAt: new Date('2026-09-11T12:01:00.000Z') })).not.toBe(
      a,
    );
  });

  it('differs per viewer, per entity, and per secret', () => {
    const a = computeTraceCode(base);
    expect(computeTraceCode({ ...base, viewerId: 'user_b' })).not.toBe(a);
    expect(computeTraceCode({ ...base, entityId: 'content_2' })).not.toBe(a);
    expect(computeTraceCode({ ...base, secret: `${base.secret}x` })).not.toBe(a);
  });

  it('separates fields so concatenation cannot alias two different pairs', () => {
    // ("ab", "c") vs ("a", "bc") — same characters, different pairs.
    const x = computeTraceCode({ ...base, entityId: 'ab', viewerId: 'c' });
    const y = computeTraceCode({ ...base, entityId: 'a', viewerId: 'bc' });
    expect(x).not.toBe(y);
  });

  it('never contains the viewer id or entity id', () => {
    const code = computeTraceCode({ ...base, viewerId: 'ZZZZ', entityId: 'YYYY' });
    expect(code).not.toContain('ZZZZ');
    expect(code).not.toContain('YYYY');
    expect(traceWatermarkLabel(code)).toBe(`${WATERMARK_BRAND} • ${code}`);
  });
});

describe('createTraceRecorder', () => {
  it('writes one AuditLog row per issue, keyed by viewer, carrying the code', async () => {
    const prisma = createFakePrisma();
    const at = new Date('2026-09-11T12:00:10.000Z');
    const recorder = createTraceRecorder({
      prisma: prisma as unknown as PrismaClient,
      secret: 'unit-test-secret-at-least-32-characters-long!!',
      now: () => at,
    });

    const first = await recorder.issue({ entity: 'Content', entityId: 'c1', viewerId: 'u1' });
    const second = await recorder.issue({ entity: 'Content', entityId: 'c1', viewerId: 'u1' });
    expect(first.traceCode).toBe(second.traceCode);
    expect(first.servedAt).toEqual(at);

    // Two serves → two rows, even though the code repeats within the minute.
    expect(prisma.__auditLogs).toHaveLength(2);
    expect(prisma.__auditLogs[0]).toMatchObject({
      actorId: 'u1',
      action: 'content.served',
      entity: 'Content',
      entityId: 'c1',
      metadata: { viewerId: 'u1', traceCode: first.traceCode, servedAt: at.toISOString() },
    });

    const gen = await recorder.issue({ entity: 'GenerationJob', entityId: 'g1', viewerId: 'u1' });
    expect(prisma.__auditLogs[2]).toMatchObject({
      action: 'generation.image_served',
      entity: 'GenerationJob',
      entityId: 'g1',
      metadata: { traceCode: gen.traceCode },
    });
  });
});

