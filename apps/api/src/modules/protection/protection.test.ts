describe('D1 — GET /api/generations/:id/image', () => {
  it('watermarks with brand + trace code (never the email), audits, and the code round-trips', async () => {
    vi.useFakeTimers({ toFake: ['Date'] });
    vi.setSystemTime(new Date('2026-09-11T12:00:10.000Z'));
    try {
      const h = await makeApp();
      const model = await loginAs(h, 'model', 'model@example.com');
      seedProfile(h.prisma, model.userId, undefined, { aiConsent: true });
      const sub = await loginAs(h, 'subscriber', 'sub.gen@example.com');
      const job = seedGenerationJob(h.prisma, { subscriberId: sub.userId, modelId: model.userId });

      const res = await h.app.inject({
        method: 'GET',
        url: `/api/generations/${job.id}/image`,
        cookies: { access_token: sub.cookie },
      });
      expect(res.statusCode).toBe(200);
      const body = res.rawPayload.toString();
      const code = codeIn(body);
      expect(body).not.toContain('sub.gen');
      expect(body).not.toContain(sub.userId);

      expect(code).toBe(
        computeTraceCode({
          secret: process.env.WATERMARK_TRACE_SECRET!,
          entityId: job.id,
          viewerId: sub.userId,
          servedAt: new Date(),
        }),
      );
      const rows = serveRows(h, 'generation.image_served');
      expect(rows).toHaveLength(1);
      expect(rows[0]).toMatchObject({
        actorId: sub.userId,
        entity: 'GenerationJob',
        entityId: job.id,
        metadata: { viewerId: sub.userId, traceCode: code },
      });
      // The stored object is untouched — the mark is applied at serve time only.
      expect(body).not.toContain(job.storageKey!);
    } finally {
      vi.useRealTimers();
    }
  });
});

