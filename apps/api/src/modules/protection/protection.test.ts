describe('env.ts — WATERMARK_TRACE_SECRET', () => {
  const original = process.env.WATERMARK_TRACE_SECRET;

  afterEach(() => {
    process.env.WATERMARK_TRACE_SECRET = original;
    vi.resetModules();
  });

  it('crashes at boot when missing', async () => {
    delete process.env.WATERMARK_TRACE_SECRET;
    vi.resetModules();
    await expect(import('../../lib/env.js')).rejects.toThrow(/WATERMARK_TRACE_SECRET/);
  });

  it('crashes at boot when shorter than 32 chars', async () => {
    process.env.WATERMARK_TRACE_SECRET = 'too-short';
    vi.resetModules();
    await expect(import('../../lib/env.js')).rejects.toThrow(/at least 32 characters/);
  });

  it('boots with a 32+ char secret', async () => {
    process.env.WATERMARK_TRACE_SECRET = 'x'.repeat(32);
    vi.resetModules();
    await expect(import('../../lib/env.js')).resolves.toBeDefined();
  });
});
