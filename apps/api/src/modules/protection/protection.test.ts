describe('D2 — GET /api/content/:contentId/serve (video, Option B)', () => {
  let h: Harness;
  let modelId: string;

  beforeEach(async () => {
    vi.useFakeTimers({ toFake: ['Date'] });
    vi.setSystemTime(new Date('2026-09-11T12:00:10.000Z'));
    h = await makeApp();
    const model = await loginAs(h, 'model', 'model@example.com');
    modelId = model.userId;
    seedProfile(h.prisma, modelId);
  });

  afterEach(() => {
    vi.useRealTimers();
  });

  it('returns the signed URL plus a traceCode from the same helper, and audits the serve', async () => {
    const alice = await loginAs(h, 'subscriber', 'alice@example.com');
    const bob = await loginAs(h, 'subscriber', 'bob@example.com');
    const v = seedContent(h.prisma, {
      modelId,
      tier: 'FREE',
      type: 'VIDEO',
      mimeType: 'video/mp4',
      storageKey: `content/${modelId}/clip.mp4`,
    });

    const resA = await serve(h, v.id, alice.cookie);
    expect(resA.statusCode).toBe(200);
    const bodyA = resA.json<{ signedUrl: string; expiresIn: number; traceCode: string }>();
    expect(bodyA.expiresIn).toBe(60);
    expect(bodyA.signedUrl).toContain('ttl=60');
    expect(bodyA.traceCode).toMatch(TRACE_RE);
    // No key in the JSON body other than inside the signed URL the client must fetch.
    expect(Object.keys(bodyA).sort()).toEqual(['expiresIn', 'signedUrl', 'traceCode']);

    // Same helper as D1: the code is exactly what computeTraceCode yields for
    // (content, viewer, this minute) under the test secret.
    expect(bodyA.traceCode).toBe(
      computeTraceCode({
        secret: process.env.WATERMARK_TRACE_SECRET!,
        entityId: v.id,
        viewerId: alice.userId,
        servedAt: new Date(),
      }),
    );

    const bodyB = (await serve(h, v.id, bob.cookie)).json<{ traceCode: string }>();
    expect(bodyB.traceCode).not.toBe(bodyA.traceCode);

    // Same audit trail as images: one row per serve, resolvable to the viewer.
    const rows = serveRows(h, 'content.served');
    expect(rows).toHaveLength(2);
    expect((resolveCode(h, bodyA.traceCode)[0].metadata as TraceMeta).viewerId).toBe(alice.userId);
    expect((resolveCode(h, bodyB.traceCode)[0].metadata as TraceMeta).viewerId).toBe(bob.userId);
    // No watermarking happens server-side for video — Option B by design.
    expect(h.images.watermark).not.toHaveBeenCalled();
  });
});

