describe('D1 — GET /api/content/:contentId/serve (image)', () => {
  let h: Harness;
  let modelId: string;

  beforeEach(async () => {
    vi.useFakeTimers({ toFake: ['Date'] });
    vi.setSystemTime(new Date('2026-09-11T12:00:10.000Z'));
    h = await makeApp();
    const model = await loginAs(h, 'model', 'model@example.com');
    modelId = model.userId;
    seedProfile(h.prisma, modelId);
  });

  afterEach(() => {
    vi.useRealTimers();
  });

  it('two subscribers viewing the same content get different codes; each is audited and round-trips', async () => {
    const alice = await loginAs(h, 'subscriber', 'alice@example.com');
    const bob = await loginAs(h, 'subscriber', 'bob@example.com');
    const c = seedContent(h.prisma, { modelId, tier: 'STANDARD' });
    grantAccess(h, c.id, alice.userId);
    grantAccess(h, c.id, bob.userId);

    const resA = await serve(h, c.id, alice.cookie);
    const resB = await serve(h, c.id, bob.cookie);
    expect(resA.statusCode).toBe(200);
    expect(resB.statusCode).toBe(200);
    expect(resA.headers['cache-control']).toBe('no-store');

    const codeA = codeIn(resA.rawPayload.toString());
    const codeB = codeIn(resB.rawPayload.toString());
    expect(codeA).not.toBe(codeB);

    // One row per serve, and the lookup lands on the right viewer.
    const rows = serveRows(h, 'content.served');
    expect(rows).toHaveLength(2);
    expect(rows.map((r) => r.entityId)).toEqual([c.id, c.id]);

    const foundA = resolveCode(h, codeA);
    expect(foundA).toHaveLength(1);
    expect(foundA[0].actorId).toBe(alice.userId);
    expect((foundA[0].metadata as TraceMeta).viewerId).toBe(alice.userId);

    const foundB = resolveCode(h, codeB);
    expect(foundB).toHaveLength(1);
    expect((foundB[0].metadata as TraceMeta).viewerId).toBe(bob.userId);
  });

  it('the same subscriber twice within a minute gets the same code, and a new one next minute', async () => {
    const alice = await loginAs(h, 'subscriber', 'alice@example.com');
    const c = seedContent(h.prisma, { modelId, tier: 'FREE' });

    const first = codeIn((await serve(h, c.id, alice.cookie)).rawPayload.toString());
    vi.setSystemTime(new Date('2026-09-11T12:00:45.000Z'));
    const second = codeIn((await serve(h, c.id, alice.cookie)).rawPayload.toString());
    expect(second).toBe(first);

    vi.setSystemTime(new Date('2026-09-11T12:01:05.000Z'));
    const third = codeIn((await serve(h, c.id, alice.cookie)).rawPayload.toString());
    expect(third).not.toBe(first);

    // Still one audit row per serve — the code de-duplicates marks, not rows.
    expect(serveRows(h, 'content.served')).toHaveLength(3);
    expect(resolveCode(h, first)).toHaveLength(2);
    expect(resolveCode(h, third)).toHaveLength(1);
  });

  it('non-leakage: the watermark text contains no substring of the viewer email or raw id', async () => {
    const alice = await loginAs(h, 'subscriber', 'alice.leaktest@example.com');
    const c = seedContent(h.prisma, { modelId, tier: 'FREE' });

    const body = (await serve(h, c.id, alice.cookie)).rawPayload.toString();
    const label = body.slice(WATERMARK_MARKER.length);
    expect(label).toMatch(LABEL_RE);

    // Every ≥4-char window of the email and of the id, case-insensitively —
    // the id alphabet overlaps base32's, so a lax check could miss a leak.
    // Windows that are themselves part of the brand word are not evidence.
    const rendered = label.toUpperCase();
    const brand = WATERMARK_BRAND.toUpperCase();
    for (const secret of [alice.email, alice.userId]) {
      const upper = secret.toUpperCase();
      for (let len = 4; len <= upper.length; len++) {
        for (let i = 0; i + len <= upper.length; i++) {
          const window = upper.slice(i, i + len);
          if (brand.includes(window)) continue;
          expect(rendered, `leaked "${window}"`).not.toContain(window);
        }
      }
    }
    // The pure form of the same property: the code is opaque without the key.
    expect(label).not.toContain(alice.userId);
    expect(label).not.toContain('alice');
    expect(label).not.toContain('example');
    // And the fake watermark received exactly that label — nothing else went to the renderer.
    expect(h.images.watermark).toHaveBeenCalledWith(
      expect.any(Buffer),
      traceWatermarkLabel(codeIn(body)),
      'image/jpeg',
    );
  });

  it('issues no trace and writes no audit row when access is denied', async () => {
    const alice = await loginAs(h, 'subscriber', 'alice@example.com');
    const c = seedContent(h.prisma, { modelId, tier: 'STANDARD' });

    const res = await serve(h, c.id, alice.cookie);
    expect(res.statusCode).toBe(403);
    expect(serveRows(h, 'content.served')).toHaveLength(0);
    expect(h.images.watermark).not.toHaveBeenCalled();
  });
});

